#!/usr/bin/env python3
"""Generate the public and operator TypeScript contracts and the fetch client into a frontend checkout."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLIENT = '''import type { PublicRoutes } from "./api-contract";

/** A public API failure; 409 tells paginated consumers to restart their result set. */
export class ApiError extends Error {
  constructor(public status: number, message: string) { super(message); }
}
/** Typed GET client. Browser requests use the same-origin backend gateway. */
export async function apiGet<P extends keyof PublicRoutes>(
  path: P, params: Record<string, string | number | boolean | null | undefined> = {}, signal?: AbortSignal,
): Promise<PublicRoutes[P]> {
  const query = new URLSearchParams();
  for (const [key, value] of Object.entries(params)) if (value != null && value !== "") query.set(key, String(value));
  const response = await fetch(`/api/v1${path}${query.size ? `?${query}` : ""}`, { signal, credentials: "same-origin", cache: "no-store" });
  if (!response.ok) {
    const body = await response.json().catch(() => ({}));
    throw new ApiError(response.status, body && typeof body === "object" && "error" in body && typeof body.error === "string" ? body.error : "Could not load results");
  }
  return response.json();
}
'''

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True, help="Frontend repository root")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = {
        "api-contract.ts": (ROOT / "contracts/public-api.ts").read_text(),
        "api-client.ts": CLIENT,
        "operator-contract.ts": (ROOT / "contracts/operator-api.ts").read_text().replace('from "./public-api"', 'from "./api-contract"'),
    }
    for name, content in generated.items():
        target = args.output / "lib" / name
        content = "// Generated by bazaar-ghost/scripts/generate_frontend_api.py. Do not edit.\n" + content
        if args.check:
            if not target.exists() or target.read_text() != content:
                raise SystemExit(f"Generated API client out of date: {target}")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)

if __name__ == "__main__":
    main()
