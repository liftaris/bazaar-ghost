"""Generates scripts/migration/post_import.sql and the legacy-group block of migration 0015 from legacy_groups.sql.

    python3 scripts/migration/gen_backfill.py           # rewrite both files
    python3 scripts/migration/gen_backfill.py --check   # exit 1 when either is stale
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'scripts/migration/legacy_groups.sql'
POST_IMPORT = ROOT / 'scripts/migration/post_import.sql'
MIGRATION = ROOT / 'worker/migrations/0015_matchup_coalescing.sql'
BEGIN = '-- BEGIN generated:legacy-groups (scripts/migration/gen_backfill.py; edit scripts/migration/legacy_groups.sql)\n'
END = '-- END generated:legacy-groups\n'

# Where the migration reads groups from the legacy table, an import reads them from the loaded appearances.
MIGRATION_PREPARE = 'CREATE TABLE m5_legacy_membership AS SELECT clip_id AS anchor_id,matchup_id AS group_id FROM clip_appearances;\n'
IMPORT_PREPARE = ('DROP TABLE IF EXISTS m5_legacy_membership;\n'
                  'CREATE TABLE m5_legacy_membership AS SELECT DISTINCT a.id AS anchor_id,ma.matchup_id AS group_id FROM matchup_appearances ma\n'
                  'JOIN detections d ON d.id=ma.detection_id JOIN matchup_anchors a ON a.vod_id=d.vod_id AND a.anchor_seconds=d.frame_time_seconds;\n')
IMPORT_HEADER = ('-- Generated by scripts/migration/gen_backfill.py from legacy_groups.sql. Run once after the import parts, before cutover.\n'
                 '-- A fresh import starts at revision 0, so the footer resets the revisions the merges bumped.\n')
IMPORT_FOOTER = 'UPDATE public_search_state SET revision=0 WHERE id=1;\nUPDATE public_cache_state SET revision=0 WHERE id=1;\n'


def body():
    return SOURCE.read_text()


def migration_block():
    return BEGIN + MIGRATION_PREPARE + body() + END


def post_import():
    return IMPORT_HEADER + BEGIN + IMPORT_PREPARE + body() + END + IMPORT_FOOTER


def render_migration(text):
    start, end = text.index(BEGIN), text.index(END) + len(END)
    return text[:start] + migration_block() + text[end:]


def main(argv):
    migration = MIGRATION.read_text()
    outputs = {POST_IMPORT: post_import(), MIGRATION: render_migration(migration)}
    if '--check' in argv:
        stale = [p.name for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            print('stale:', ', '.join(stale))
            return 1
        return 0
    for path, text in outputs.items():
        path.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
